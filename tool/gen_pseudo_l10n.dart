// Writes test/support/pseudo_l10n.dart: every interface message, passed
// through English and then pseudo-localised (test/support/pseudo.dart).
//
//     fvm dart run tool/gen_pseudo_l10n.dart
//
// Run it after adding or changing a message in lib/l10n/app_en.arb — the
// generated class stops compiling the moment `L` gains a member it does not
// override, and `l10n_test` fails if it is merely out of date. It is test-only:
// no pseudo-locale ships in the app.

import 'dart:io';

const _abstract = 'lib/l10n/generated/l10n.dart';
const _target = 'test/support/pseudo_l10n.dart';

void main() {
  File(_target).writeAsStringSync(pseudoL10nSource(File(_abstract).readAsStringSync()));
  stdout.writeln('wrote $_target');
}

/// The source of `PseudoL`, from the generated abstract `L`. Every message
/// there is one line: `String get name;` or `String name(Type a, Type b);`.
String pseudoL10nSource(String abstractL) {
  final members = RegExp(r'^  String (?:get (\w+)|(\w+)\(([^)]*)\));$', multiLine: true);
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_pseudo_l10n.dart from $_abstract. Do not edit.')
    ..writeln()
    ..writeln("import 'package:sprawl_run/l10n/generated/l10n_en.dart';")
    ..writeln("import 'package:sprawl_run/l10n/l10n.dart';")
    ..writeln()
    ..writeln("import 'pseudo.dart';")
    ..writeln()
    ..writeln('/// English, made to measure like a translation; see [pseudo].')
    ..writeln('class PseudoL extends L {')
    ..writeln("  PseudoL() : super('en_XA');")
    ..writeln()
    ..writeln('  final _en = LEn();');
  for (final m in members.allMatches(abstractL)) {
    out.writeln();
    out.writeln('  @override');
    if (m.group(1) case final name?) {
      out.writeln('  String get $name => pseudo(_en.$name);');
    } else {
      final name = m.group(2)!;
      final params = m.group(3)!;
      final args = params.split(',').map((p) => p.trim().split(' ').last).join(', ');
      out.writeln('  String $name($params) => pseudo(_en.$name($args));');
    }
  }
  out.writeln('}');
  return out.toString();
}
